"""Build data-driven validation limits for every live tag.

    python -m etl.build_validation_limits

Output: data/validation_limits.json, read by backend/validation.py.

Limits come from the plant's own behaviour, not guesses:
  - range  : production history (kiln feed above the advisor threshold).
             rare  = outside the 0.1 - 99.9 percentile band  -> WARNING
             hard  = beyond that band widened by 25% of its span, and never
                     below 0 for a tag that has never been negative -> ERROR
  - spike  : the largest plausible move of a reading away from its own recent
             median, = the 99.9th percentile of minute-to-minute changes
  - stuck  : how long the value normally sits exactly unchanged in the LIVE
             feed (2 s samples, same source and cadence the backend checks);
             stuck = 3 x the 99th percentile of those flat runs, at least
             10 min, at most 6 h. A tag that legitimately sits still for long
             (e.g. a speed setpoint) therefore gets a long allowance.

process_1min (Aug 2025 - Jul 2026, 1-min) is used for range and spike where a
tag has history there; process_live (raw OPC, 2 s) otherwise and for stuck.
"""
from __future__ import annotations

import json
import sqlite3
from datetime import date
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DB = ROOT / "data" / "digital_twin.sqlite"
OUT = ROOT / "data" / "validation_limits.json"
SKIP = {"ts", "feed_gate", "source", "index"}
MIN_ROWS = 2000


def _range_and_step(s: pd.Series, minutes_per_row: float) -> dict | None:
    s = pd.to_numeric(s, errors="coerce").dropna()
    if len(s) < MIN_ROWS:
        return None
    p001, p999 = float(s.quantile(0.001)), float(s.quantile(0.999))
    span = max(p999 - p001, 1e-6)
    hard_lo, hard_hi = p001 - 0.25 * span, p999 + 0.25 * span
    if float(s.min()) >= 0:
        hard_lo = max(hard_lo, 0.0)
    d = s.diff().abs().dropna()
    step = float(d.quantile(0.999)) / max(minutes_per_row, 1e-9) if len(d) else None
    k5 = max(int(round(5 / minutes_per_row)), 1)                 # rows per 5 minutes
    d5 = (s.shift(-k5) - s).abs().dropna()
    return {"n": int(len(s)), "median": float(s.median()), "p001": p001, "p999": p999,
            "hard_lo": hard_lo, "hard_hi": hard_hi, "step_1min": step,
            "move5_p99": float(d5.quantile(0.99)) if len(d5) else None,
            "move5_p999": float(d5.quantile(0.999)) if len(d5) else None,
            "nonneg": bool(float(s.min()) >= 0), "std": float(s.std())}


def _flat_runs_seconds(ts: pd.Series, v: pd.Series) -> list[float]:
    """Durations (s) of runs of exactly identical consecutive values, split at feed gaps."""
    df = pd.DataFrame({"t": pd.to_datetime(ts, format="mixed", errors="coerce"),
                       "v": pd.to_numeric(v, errors="coerce")}).dropna()
    if len(df) < MIN_ROWS:
        return []
    gap = df["t"].diff().dt.total_seconds().fillna(9e9) > 10
    change = df["v"].ne(df["v"].shift()) | gap
    run_id = change.cumsum()
    g = df.groupby(run_id)["t"].agg(["min", "max", "size"])
    g = g[g["size"] >= 2]
    return ((g["max"] - g["min"]).dt.total_seconds()).tolist()


def build() -> dict:
    con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
    hist_cols = [r[1] for r in con.execute("PRAGMA table_info(process_1min)")]
    live_cols = [r[1] for r in con.execute("PRAGMA table_info(process_live)")]
    tags = sorted((set(hist_cols) | set(live_cols)) - SKIP)
    hist = pd.read_sql("SELECT * FROM process_1min WHERE feed_gate = 1", con)
    live = pd.read_sql("SELECT * FROM process_live", con)
    con.close()
    live_prod = live[pd.to_numeric(live.get("353RL130_TPH"), errors="coerce") > 461] if "353RL130_TPH" in live else live

    out = {}
    for t in tags:
        src = None
        st = _range_and_step(hist[t], 1.0) if t in hist else None
        if st:
            src = "process_1min"
        elif t in live_prod:
            st = _range_and_step(live_prod[t], 2 / 60)     # live rows are ~2 s apart
            src = "process_live"
        if not st:
            continue
        runs = _flat_runs_seconds(live["ts"], live[t]) if t in live else []
        p99 = float(np.percentile(runs, 99)) if runs else 0.0
        st["stuck_after_s"] = float(min(max(3 * p99, 600.0), 6 * 3600.0))
        st["flat_run_p99_s"] = p99
        st["source"] = src
        out[t] = {k: (round(v, 4) if isinstance(v, float) else v) for k, v in st.items()}
    return {"_about": "Generated by etl/build_validation_limits.py from plant history; do not hand-edit "
                      "(re-run the script instead). See backend/validation.py for how each field is used.",
            "_generated": date.today().isoformat(),
            "_rows": {"process_1min_production": int(len(hist)), "process_live": int(len(live))},
            "tags": out}


if __name__ == "__main__":
    res = build()
    OUT.write_text(json.dumps(res, indent=1), encoding="utf-8")
    print(f"wrote {OUT}  ({len(res['tags'])} tags; history {res['_rows']})")
