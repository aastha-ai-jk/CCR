<#
CCR advisor kiosk — Windows edge device (display only).

Run ONCE, as the kiosk user (the account that auto-logs-in on the CCR screen),
in an elevated PowerShell only if you also want the power settings applied
machine-wide. It:
  1. checks the device can reach the advisor on the GPU server,
  2. installs a watchdog that keeps Microsoft Edge open full-screen (kiosk mode)
     on the advisor and relaunches it if it is closed or crashes,
  3. registers the watchdog to start at log-on,
  4. stops the display and the PC from sleeping.
Nothing is installed on the GPU server; the screen only reads http://<server>.

  powershell -ExecutionPolicy Bypass -File setup-kiosk.ps1
  powershell -ExecutionPolicy Bypass -File setup-kiosk.ps1 -Url http://10.53.2.10:8010/advisor -SecondUrl http://10.53.2.10:3010/twin
  powershell -ExecutionPolicy Bypass -File setup-kiosk.ps1 -Remove
#>
param(
    [string]$Url = "http://10.53.2.10:8010/advisor",
    [string]$SecondUrl = "",          # optional 2nd screen, e.g. http://10.53.2.10:3010/twin
    [switch]$Remove
)
$ErrorActionPreference = "Stop"
$dir = Join-Path $env:LOCALAPPDATA "CCRKiosk"
$watchdog = Join-Path $dir "kiosk-watchdog.ps1"
$taskName = "CCR Advisor Kiosk"

if ($Remove) {
    Unregister-ScheduledTask -TaskName $taskName -Confirm:$false -ErrorAction SilentlyContinue
    Remove-Item $dir -Recurse -Force -ErrorAction SilentlyContinue
    Write-Host "Kiosk removed (log off to close the open kiosk window)."
    return
}

# 1. reachability
$u = [Uri]$Url
$ok = Test-NetConnection $u.Host -Port $u.Port -WarningAction SilentlyContinue -InformationLevel Quiet
Write-Host ("Reach {0}:{1} -> {2}" -f $u.Host, $u.Port, $(if ($ok) { "OK" } else { "NOT REACHABLE - ask IT to open this port from the CCR network" }))

# 2. watchdog: (re)launch Edge in kiosk mode, one window per screen
$edge = @("${env:ProgramFiles(x86)}\Microsoft\Edge\Application\msedge.exe",
          "$env:ProgramFiles\Microsoft\Edge\Application\msedge.exe") | Where-Object { Test-Path $_ } | Select-Object -First 1
if (-not $edge) { throw "Microsoft Edge not found." }
New-Item -ItemType Directory -Force $dir | Out-Null
@"
# Generated by setup-kiosk.ps1 - keeps the CCR advisor on screen.
Add-Type -AssemblyName System.Windows.Forms
`$edge = '$edge'
`$screens = [System.Windows.Forms.Screen]::AllScreens
`$pages = @(@{ url = '$Url'; profile = 'kiosk1'; x = `$screens[0].Bounds.X })
if ('$SecondUrl' -and `$screens.Count -gt 1) { `$pages += @{ url = '$SecondUrl'; profile = 'kiosk2'; x = `$screens[1].Bounds.X } }
while (`$true) {
    foreach (`$p in `$pages) {
        `$data = Join-Path '$dir' `$p.profile
        `$running = Get-CimInstance Win32_Process -Filter "Name='msedge.exe'" | Where-Object { `$_.CommandLine -like "*`$data*" }
        if (-not `$running) {
            Start-Process `$edge -ArgumentList @('--kiosk', `$p.url, '--edge-kiosk-type=fullscreen',
                '--no-first-run', '--disable-features=Translate', "--user-data-dir=`$data",
                "--window-position=`$(`$p.x),0")
        }
    }
    Start-Sleep -Seconds 15
}
"@ | Set-Content -Path $watchdog -Encoding UTF8

# 3. start at log-on (current user, hidden)
$action = New-ScheduledTaskAction -Execute "powershell.exe" -Argument "-NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File `"$watchdog`""
$trigger = New-ScheduledTaskTrigger -AtLogOn -User "$env:USERDOMAIN\$env:USERNAME"
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -ExecutionTimeLimit ([TimeSpan]::Zero) -RestartCount 999 -RestartInterval (New-TimeSpan -Minutes 1)
Register-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger -Settings $settings -Force | Out-Null
Write-Host "Watchdog registered to start at log-on: $taskName"

# 4. never sleep / blank
powercfg /change monitor-timeout-ac 0
powercfg /change standby-timeout-ac 0
powercfg /change hibernate-timeout-ac 0
Set-ItemProperty -Path "HKCU:\Control Panel\Desktop" -Name ScreenSaveActive -Value "0"
Write-Host "Display/standby sleep disabled, screen saver off."

Start-ScheduledTask -TaskName $taskName
Write-Host "Kiosk started. Exit a kiosk window with Alt+F4 (the watchdog reopens it in ~15 s); remove with -Remove."
